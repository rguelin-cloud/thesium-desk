def validate_py(path: str) -> bool:
    with open(path, "rb") as f:
        data = f.read()
    # ASCII check
    for i, b in enumerate(data):
        if b > 127:
            log(f"  FAIL ASCII at offset {i}")
            return False
    try:
        ast.parse(data.decode("utf-8"))
    except SyntaxError as e:
        log(f"  FAIL AST: {e}")
        return False
    try:
        py_compile.compile(path, doraise=True)
    except py_compile.PyCompileError as e:
        log(f"  FAIL py_compile: {e}")
        return False
    return True


def deploy_file(key: str, target_dir: str) -> bool:
    info = ASSETS[key]
    raw = base64.b64decode(info["b64"])
    if len(raw) != info["size"]:
        log(f"  FAIL size mismatch {key}: got {len(raw)} expected {info['size']}")
        return False
    sha = hashlib.sha256(raw).hexdigest()[:16]
    if sha != info["sha256_16"]:
        log(f"  FAIL sha mismatch {key}: got {sha} expected {info['sha256_16']}")
        return False

    target = os.path.join(target_dir, key)
    # Backup existing
    if os.path.exists(target):
        ts = datetime.datetime.now().strftime("%Y%m%d%H%M%S")
        backup = target + f".bak.{ts}"
        shutil.copy2(target, backup)
        log(f"  backup -> {os.path.basename(backup)}")

    # Write
    with open(target, "wb") as f:
        f.write(raw)
    log(f"  wrote {key} ({len(raw)} bytes, sha={sha})")

    # Validate .py
    if key.endswith(".py"):
        if not validate_py(target):
            log(f"  FAIL validation {key}")
            return False
        log(f"  validation PASS")

    return True


def apply_schema(db_path: str, sql_path: str) -> bool:
    log(f"\nSchema SQL : {sql_path}")
    if not os.path.exists(sql_path):
        log(f"  FAIL : SQL file not found")
        return False
    with open(sql_path, "r", encoding="utf-8") as f:
        sql = f.read()

    try:
        conn = sqlite3.connect(db_path, timeout=10.0)
        conn.execute("PRAGMA journal_mode=WAL")
        conn.executescript(sql)
        conn.commit()

        # Verify
        cur = conn.cursor()
        for tbl in ["replay_orders", "replay_fills", "replay_positions", "replay_nav_history"]:
            row = cur.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name=?", (tbl,)
            ).fetchone()
            if row:
                log(f"  table {tbl} OK")
            else:
                log(f"  FAIL table {tbl} missing")
                conn.close()
                return False
        conn.close()
        return True
    except Exception as e:
        log(f"  FAIL apply_schema: {e}")
        return False


