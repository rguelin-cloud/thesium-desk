FILES = [
    ("replay_db_view.py", REPLAY_DB_VIEW_B64, 9541),
    ("replay_orchestrator.py", REPLAY_ORCHESTRATOR_B64, 19694),
]


def main():
    print("=" * 72)
    print(" INSTALL 8B.2 (embedded) - replay_db_view + replay_orchestrator v5")
    print("=" * 72)
    print("Target :", PROD_DIR)
    print()

    if not os.path.isdir(PROD_DIR):
        print("ERR : dossier prod introuvable :", PROD_DIR)
        return 1

    stamp = datetime.now().strftime("%Y%m%d%H%M%S")

    for fname, b64, expected_size in FILES:
        dst = os.path.join(PROD_DIR, fname)
        print("  [%s]" % fname)

        # Decode
        data = base64.b64decode(b64)
        new_size = len(data)
        print("    embedded size : %d bytes (expected %d)" % (new_size, expected_size))

        if new_size != expected_size:
            print("    ERR size mismatch !")
            return 1

        # Backup si existant
        if os.path.exists(dst):
            old_size = os.path.getsize(dst)
            bak = dst + ".bak." + stamp
            shutil.copy2(dst, bak)
            print("    old size      : %d bytes" % old_size)
            print("    backup        : %s" % bak)
        else:
            print("    old size      : (absent)")

        # Write
        with open(dst, "wb") as f:
            f.write(data)
        wrote = os.path.getsize(dst)
        print("    installed     : %d bytes" % wrote)
        print()

    # Validation : marqueurs v5
    print("=" * 72)
    print(" VALIDATION post-install")
    print("=" * 72)

    rdv = os.path.join(PROD_DIR, "replay_db_view.py")
    with open(rdv, "rb") as f:
        content = f.read().decode("utf-8")
    markers = ["static_tables", "state_tables", "theses",
               "convergence_snapshots", "portfolio_state"]
    print("Marqueurs v5 dans replay_db_view.py :")
    ok_all = True
    for m in markers:
        found = m in content
        flag = "OK  " if found else "MISS"
        print("  [%s] %s" % (flag, m))
        if not found:
            ok_all = False

    ro = os.path.join(PROD_DIR, "replay_orchestrator.py")
    with open(ro, "rb") as f:
        content2 = f.read().decode("utf-8")
    markers2 = ["_export_convergence_snapshots", "_export_targets",
                "run_construction_agent", "compute_convergence"]
    print()
    print("Marqueurs v2 (8B.2) dans replay_orchestrator.py :")
    for m in markers2:
        found = m in content2
        flag = "OK  " if found else "MISS"
        print("  [%s] %s" % (flag, m))
        if not found:
            ok_all = False

    print()
    if ok_all:
        print("INSTALL OK. Lance :")
        print("  py -3.13 .\\nextones-run-replay-8b2-v1.py")
        return 0
    else:
        print("INSTALL INCOMPLET (markers manquants).")
        return 1


if __name__ == "__main__":
    sys.exit(main())
